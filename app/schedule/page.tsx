"use client";

import { Suspense, useEffect, useRef, useState } from "react";
import { useSearchParams } from "next/navigation";
import { Loader2, Sparkles } from "lucide-react";
import { useMutation, useQuery } from "convex/react";
import { api } from "../../convex/_generated/api";
import type { Doc, Id } from "../../convex/_generated/dataModel";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import {
  RecommendationCard,
  type Recommendation,
} from "@/components/shared/RecommendationCard";
import { PageHeader } from "@/components/shared/PageHeader";
import { getGroqRecommendation } from "@/lib/groq";
import { useHaptic } from "@/hooks/useHaptic";
import { useGeolocation } from "@/hooks/useGeolocation";

interface PlanArgs {
  soilType: string;
  cropType: string;
  plantingDate: string;
  location?: string;
  seedLabel?: string;
}

function ScheduleContent() {
  const { impact } = useHaptic();
  const geo = useGeolocation();
  const searchParams = useSearchParams();
  const seedParam = searchParams.get("seed");

  const [userId, setUserId] = useState<Id<"users"> | null>(null);
  const [soilType, setSoilType] = useState("");
  const [cropType, setCropType] = useState("");
  const [plantingDate, setPlantingDate] = useState("");
  const [location, setLocation] = useState("");
  const [recommendation, setRecommendation] = useState<Recommendation | null>(null);
  const [planTitle, setPlanTitle] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const ensureUser = useMutation(api.users.ensure);
  const saveSchedule = useMutation(api.recommendations.save);
  const history = useQuery(
    api.recommendations.listByUser,
    userId ? { userId } : "skip"
  );
  const seedId = seedParam as Id<"seeds"> | null;
  const seed = useQuery(api.seeds.get, seedId ? { seedId } : "skip");
  const latestReading = useQuery(
    api.sensorReadings.latestForSeed,
    seedId ? { seedId } : "skip"
  );

  const autoGeneratedFor = useRef<string | null>(null);

  useEffect(() => {
    let cancelled = false;
    void ensureUser()
      .then((id) => {
        if (!cancelled) setUserId(id);
      })
      .catch(() => {
        if (!cancelled) setError("Backend unavailable");
      });
    return () => {
      cancelled = true;
    };
  }, [ensureUser]);

  const locateRef = useRef(geo.locate);
  locateRef.current = geo.locate;

  useEffect(() => {
    let cancelled = false;
    void locateRef.current().then((place) => {
      if (place && !cancelled) {
        setLocation(place.label);
      }
    });
    return () => {
      cancelled = true;
    };
  }, []);

  const runGenerate = async (args: PlanArgs) => {
    if (!args.soilType.trim() || !args.cropType.trim() || !args.plantingDate) {
      setError("Fill all fields");
      return;
    }
    setLoading(true);
    setError(null);
    try {
      const data = await getGroqRecommendation({
        soilType: args.soilType.trim(),
        cropType: args.cropType.trim(),
        plantingDate: args.plantingDate,
        location: args.location?.trim() || undefined,
      });
      setRecommendation(data);
      setPlanTitle(args.seedLabel ?? null);
      impact("light");
      if (userId) {
        void saveSchedule({
          userId,
          soilType: args.soilType.trim(),
          cropType: args.cropType.trim(),
          plantingDate: args.plantingDate,
          location: args.location?.trim() || undefined,
          fertilizerAdvice: data.fertilizerAdvice,
          irrigationSchedule: data.irrigationSchedule,
          runoffWarning: data.runoffWarning,
        }).catch(() => {
          // history save is best-effort; UI already has the result
        });
      }
    } catch {
      setError("Failed to get recommendation. Check GROQ_API_KEY.");
    } finally {
      setLoading(false);
    }
  };

  const runRef = useRef(runGenerate);
  runRef.current = runGenerate;

  useEffect(() => {
    if (!seed || autoGeneratedFor.current === seed._id) return;
    autoGeneratedFor.current = seed._id;
    const seedLabel = `${seed.name} · ${seed.variety}`;
    setSoilType(seed.soilType);
    setCropType(seed.name);
    setPlantingDate(seed.datePlanted);
    const seedLocation = seed.location || seed.farmName;
    if (!location.trim()) setLocation(seedLocation);
    void runRef.current({
      soilType: seed.soilType,
      cropType: `${seed.name} (${seed.variety})`,
      plantingDate: seed.datePlanted,
      location: seedLocation,
      seedLabel,
    });
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [seed]);

  const useMyLocation = async () => {
    const place = await geo.refresh();
    if (place) {
      setLocation(place.label);
    }
  };

  const generate = () => {
    void runGenerate({
      soilType,
      cropType,
      plantingDate,
      location: location.trim() || undefined,
      seedLabel: planTitle ?? undefined,
    });
  };

  const latestSaved = history?.[0];
  const seedDoc = seed as Doc<"seeds"> | null | undefined;

  return (
    <main className="flex min-h-screen flex-col bg-white pb-8">
      <PageHeader
        eyebrow="AI · Runoff plan"
        title={planTitle ?? "Guardian Schedule"}
        subtitle={
          planTitle
            ? "Plan generated for this seed"
            : "Tap a seed on Home for its plan"
        }
      />

      <div className="flex flex-col gap-4 px-5 pt-4">
        {seedDoc && (
          <p className="rounded-xl border border-emerald-200 bg-emerald-50 px-3.5 py-2.5 text-xs font-medium text-emerald-900">
            Plan for {seedDoc.name} · {seedDoc.variety} · {seedDoc.farmName}
            {latestReading && (
              <span className="ml-2 text-xs font-normal">
                · Soil {latestReading.soilTemperatureC.toFixed(1)}°C
              </span>
            )}
          </p>
        )}

        <section className="rounded-2xl border border-zinc-200 bg-white p-4">
          <h2 className="flex items-center gap-2 text-xs font-bold uppercase tracking-wide text-zinc-500">
            <Sparkles className="h-4 w-4 text-violet-600" aria-hidden />
            Farm context
          </h2>
          <div className="mt-3 flex flex-col gap-3">
            <Input placeholder="Soil type" value={soilType} onChange={(e) => setSoilType(e.target.value)} />
            <Input placeholder="Crop type" value={cropType} onChange={(e) => setCropType(e.target.value)} />
            <Input
              type="date"
              value={plantingDate}
              onChange={(e) => setPlantingDate(e.target.value)}
            />
            <Input
              placeholder={geo.loading ? "Locating…" : "Location (auto-filled)"}
              value={location}
              onChange={(e) => setLocation(e.target.value)}
            />
            <Button
              type="button"
              variant="outline"
              onClick={useMyLocation}
              disabled={geo.loading}
              className="w-full"
            >
              {geo.loading ? (
                <>
                  <Loader2 className="mr-2 h-4 w-4 animate-spin" aria-hidden />
                  Locating…
                </>
              ) : (
                "Refresh location"
              )}
            </Button>
            {geo.error && <p className="text-sm text-red-600">{geo.error}</p>}
            <Button onClick={generate} disabled={loading} className="w-full">
              {loading ? (
                <>
                  <Loader2 className="mr-2 h-4 w-4 animate-spin" aria-hidden />
                  Generating seed plan…
                </>
              ) : (
                planTitle
                  ? "Regenerate plan for this seed"
                  : "Get runoff plan"
              )}
            </Button>
            {error && <p className="text-sm text-red-600">{error}</p>}
          </div>
        </section>

        {recommendation && (
          <section className="space-y-2">
            {planTitle && (
              <h2 className="px-0.5 text-xs font-bold uppercase tracking-wide text-zinc-500">
                Plan · {planTitle}
              </h2>
            )}
            <RecommendationCard data={recommendation} />
          </section>
        )}

        {!recommendation && !loading && latestSaved && (
          <section className="space-y-2">
            <h2 className="px-0.5 text-xs font-bold uppercase tracking-wide text-zinc-500">
              Last saved plan
            </h2>
            <RecommendationCard
              data={{
                fertilizerAdvice: latestSaved.fertilizerAdvice,
                irrigationSchedule: latestSaved.irrigationSchedule,
                runoffWarning: latestSaved.runoffWarning,
              }}
            />
          </section>
        )}

        {loading && !recommendation && (
          <p className="rounded-2xl border border-dashed border-zinc-200 p-4 text-center text-sm text-zinc-500">
            Building AI plan for this seed…
          </p>
        )}
      </div>
    </main>
  );
}

export default function SchedulePage() {
  return (
    <Suspense
      fallback={
        <main className="flex min-h-screen items-center justify-center bg-white text-sm text-zinc-500">
          Loading…
        </main>
      }
    >
      <ScheduleContent />
    </Suspense>
  );
}
